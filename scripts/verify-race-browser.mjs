import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";

const library = process.env.PLAYWRIGHT_MODULE;
const { chromium } = await import(library ? pathToFileURL(library).href : "playwright");
const browser = await chromium.launch({ headless:true, channel:"chrome" });
const output = new URL("../output/playwright/",import.meta.url);
await mkdir(output,{recursive:true});
const errors=[];
try {
  const page=await browser.newPage({viewport:{width:1440,height:1050}});
  page.on("pageerror",error=>errors.push(error.message));
  await page.goto(process.env.RACE_URL||"http://localhost:3000/",{waitUntil:"networkidle"});
  await page.waitForFunction(()=>typeof window.__degenKart==="function");
  assert.equal(await page.locator("canvas").count(),1);
  assert.equal(await page.locator('img[src*="neon-circuit"]').count(),0);
  await page.screenshot({path:new URL("01-grid.png",output).pathname.replace(/^\/([A-Z]:)/,"$1"),fullPage:true});
  await page.getByText("Demo controls",{exact:true}).click();
  await page.getByRole("button",{name:"New demo lobby",exact:true}).click();
  await page.getByRole("button",{name:"New demo lobby",exact:true}).click();
  await page.getByRole("button",{name:"Play",exact:true}).click();
  await page.getByRole("button",{name:"Fill empty karts with AI & start",exact:true}).click();
  await page.waitForFunction(()=>window.__degenKart().phase==="racing");
  const initial=await page.evaluate(()=>window.__degenKart());
  assert.equal(initial.player.speed,0);
  const beforePixels=await page.locator("canvas").screenshot();
  await page.keyboard.down("w");
  await page.waitForTimeout(1350);
  await page.keyboard.up("w");
  const moved=await page.evaluate(()=>window.__degenKart());
  assert.ok(moved.player.speed>15,`accelerator speed: ${moved.player.speed}`);
  assert.ok(Math.hypot(moved.player.x-initial.player.x,moved.player.z-initial.player.z)>10,"player moved in world coordinates");
  assert.ok(Math.hypot(moved.camera.x-initial.camera.x,moved.camera.z-initial.camera.z)>10,"camera followed player position");
  assert.ok(!beforePixels.equals(await page.locator("canvas").screenshot()),"rendered world changed");
  await page.screenshot({path:new URL("02-driving.png",output).pathname.replace(/^\/([A-Z]:)/,"$1"),fullPage:true});
  await page.keyboard.down("d");await page.waitForTimeout(220);await page.keyboard.up("d");
  const turned=await page.evaluate(()=>window.__degenKart());
  assert.ok(turned.player.yaw>moved.player.yaw+.05,"steering changes actual yaw");
  await page.keyboard.down("s");await page.waitForTimeout(1000);await page.keyboard.up("s");
  const stopped=await page.evaluate(()=>window.__degenKart());assert.ok(stopped.player.speed<1,"braking stops the kart");
  await page.keyboard.press("p");const paused=await page.evaluate(()=>window.__degenKart());
  await page.waitForTimeout(250);const frozen=await page.evaluate(()=>window.__degenKart());
  assert.equal(paused.time,frozen.time);assert.equal(paused.paused,true);
  await page.getByRole("button",{name:"RESUME RACE"}).click();
  const gas=page.getByRole("button",{name:"ACCELERATE",exact:true});const rect=await gas.boundingBox();
  await page.mouse.move(rect.x+rect.width/2,rect.y+rect.height/2);await page.mouse.down();await page.waitForTimeout(400);
  assert.equal((await page.evaluate(()=>window.__degenKart())).input.throttle,true);
  await page.mouse.up();assert.equal((await page.evaluate(()=>window.__degenKart())).input.throttle,false);
  await page.getByRole("button",{name:"New demo lobby",exact:true}).click();
  await page.getByRole("button",{name:"New demo lobby",exact:true}).click();
  assert.equal((await page.evaluate(()=>window.__degenKart())).phase,"ready");
  await page.setViewportSize({width:390,height:844});
  await page.waitForTimeout(150);
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
  assert.equal(overflow,false,"mobile layout does not scroll sideways");
  await page.screenshot({path:new URL("03-mobile.png",output).pathname.replace(/^\/([A-Z]:)/,"$1"),fullPage:true});
  assert.deepEqual(errors,[]);
  const report={status:"passed",checks:["canvas renderer","no static track image","countdown","keyboard acceleration","world and chase camera translation","changed rendered frame","steering yaw","braking","pause freezes time","pointer controls and release","restart","mobile width","no browser errors"],initial,moved,turned,stopped,errors};
  await writeFile(new URL("browser-report.json",output),JSON.stringify(report,null,2));
  console.log(JSON.stringify({status:report.status,checks:report.checks,speed:moved.player.speed,worldDistance:Math.hypot(moved.player.x-initial.player.x,moved.player.z-initial.player.z)}));
} finally { await browser.close(); }
